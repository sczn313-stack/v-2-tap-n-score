import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const modulePath = fileURLToPath(import.meta.url);
const moduleDir = path.dirname(modulePath);
const root = path.resolve(moduleDir, "..");
const sourcePath = path.join(
  root,
  "backend",
  "registries",
  "military_weapon_equipment_registry.json"
);
const outputPath = path.join(root, "production", "generated_weapon_equipment_registry.mjs");

export async function generateWeaponEquipmentRegistry() {
  const sourceBytes = await readFile(sourcePath);
  const registry = JSON.parse(sourceBytes.toString("utf8"));
  const sourceSha256 = createHash("sha256").update(sourceBytes).digest("hex");
  const moduleSource = `// Generated from backend/registries/military_weapon_equipment_registry.json.
// Do not edit this file directly.
export const WEAPON_EQUIPMENT_REGISTRY_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};
export const WEAPON_EQUIPMENT_REGISTRY = Object.freeze(${JSON.stringify(registry, null, 2)});

const RECORDS_BY_ID = new Map(
  WEAPON_EQUIPMENT_REGISTRY.records.map((record) => [record.recordId, record])
);

export function getEquipmentRecord(recordId) {
  return RECORDS_BY_ID.get(String(recordId || "")) || null;
}

export function resolveProvenEquipmentRecord(recordId, adjustmentSystem = "") {
  const record = getEquipmentRecord(recordId);
  if (!record || String(record.status || "").toLowerCase() !== "proven") return null;
  if (
    adjustmentSystem
    && String(record.adjustmentSystem || "").toUpperCase() !== String(adjustmentSystem).toUpperCase()
  ) return null;
  return record;
}
`;
  await writeFile(outputPath, moduleSource);
  return { outputPath, sourceSha256, recordCount: registry.records.length };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = await generateWeaponEquipmentRegistry();
  console.log(
    `Generated ${result.recordCount} Weapon Equipment Registry record(s) · ${result.sourceSha256}`
  );
}
