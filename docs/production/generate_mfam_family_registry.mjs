import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const modulePath = fileURLToPath(import.meta.url);
const moduleDir = path.dirname(modulePath);
const root = path.resolve(moduleDir, "..");
const sourcePath = path.join(root, "backend", "registries", "mfam_family_authority.json");
const outputPath = path.join(root, "production", "generated_mfam_family_registry.mjs");
const parityOutputPath = path.join(root, "backend", "m4_authority", "parity", "generated_mfam_family_registry.mjs");

export async function generateMFAMFamilyRegistry() {
  const sourceBytes = await readFile(sourcePath);
  const registry = JSON.parse(sourceBytes.toString("utf8"));
  if (registry.schemaId !== "sczn3-mfam-authority-v2" || registry.status !== "governed") {
    throw new Error("M/FAM runtime authority registry is not governed.");
  }
  const sourceSha256 = createHash("sha256").update(sourceBytes).digest("hex");
  const packages = new Map(
    (registry.familyAuthorityPackages || [])
      .map((record) => [record.familyAuthorityPackageId, record])
  );
  const targetProfiles = Object.fromEntries(
    (registry.targetProfileBindings || [])
      .map((binding) => [
        binding.targetProfileId,
        {
          familyAuthorityPackage: packages.get(binding.familyAuthorityPackageId),
          binding
        }
      ])
  );
  if (Object.values(targetProfiles).some((record) => !record.familyAuthorityPackage)) {
    throw new Error("Governed M/FAM binding references a missing family authority package.");
  }
  const moduleSource = `// Generated from backend/registries/mfam_family_authority.json.
// Do not edit this file directly.
export const MFAM_FAMILY_REGISTRY_SOURCE_SHA256 = ${JSON.stringify(sourceSha256)};
const TARGET_PROFILES = Object.freeze(${JSON.stringify(targetProfiles, null, 2)});

export function resolveMFAMFamilyTargetProfile(targetProfileId) {
  return TARGET_PROFILES[String(targetProfileId || "").toLowerCase()] || null;
}
`;
  await Promise.all([
    writeFile(outputPath, moduleSource),
    writeFile(parityOutputPath, moduleSource)
  ]);
  return {
    outputPath,
    parityOutputPath,
    sourceSha256,
    targetProfileCount: Object.keys(targetProfiles).length
  };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = await generateMFAMFamilyRegistry();
  console.log(
    `Generated ${result.targetProfileCount} M/FAM family Target Profile(s) · ${result.sourceSha256}`
  );
}
